main() {
    print_status "Starting Home Automation Stack Setup"
    echo ""
    
    check_prerequisites
    setup_directories
    generate_configs
    setup_mqtt_auth
    start_services
    display_access_info
    
    print_status "Setup complete!"
    print_status "Remember to change all default passwords before production use."
}

main "$@"
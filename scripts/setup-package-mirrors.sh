#!/usr/bin/env bash
# =============================================================================
# Package Manager Mirror Setup for CN Networks
# Configures apt (Ubuntu/Debian) and apk (Alpine) to use Chinese mirrors
# =============================================================================
set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
BOLD='\033[1m'
NC='\033[0m'

log_info()  { echo -e "${GREEN}[INFO]${NC} $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC} $*"; }
log_error() { echo -e "${RED}[ERROR]${NC} $*" >&2; }

# Backup directory
BACKUP_DIR="/tmp/pkg-mirror-backup-$(date +%Y%m%d_%H%M%S)"

# =============================================================================
# Ubuntu/Debian APT Mirror Setup
# =============================================================================
setup_ubuntu_mirrors() {
  log_info "检测到 Ubuntu/Debian 系统"
  
  if [[ $EUID -ne 0 ]]; then
    log_error "需要 root 权限来修改 apt 源"
    return 1
  fi
  
  # Detect Ubuntu version
  local codename
  codename=$(lsb_release -cs 2>/dev/null || grep "VERSION_CODENAME" /etc/os-release | cut -d= -f2)
  
  if [[ -z "$codename" ]]; then
    log_error "无法检测 Ubuntu 版本"
    return 1
  fi
  
  log_info "系统版本: $codename"
  
  # Backup original sources.list
  if [[ -f "/etc/apt/sources.list" ]]; then
    mkdir -p "$BACKUP_DIR"
    cp /etc/apt/sources.list "$BACKUP_DIR/sources.list"
    log_info "已备份原始配置到: $BACKUP_DIR/sources.list"
  fi
  
  # Backup sources.list.d
  if [[ -d "/etc/apt/sources.list.d" ]]; then
    cp -r /etc/apt/sources.list.d "$BACKUP_DIR/"
    log_info "已备份 sources.list.d 目录"
  fi
  
  # Generate new sources.list with TUNA mirror (清华源)
  cat > /etc/apt/sources.list <<EOF
# 清华大学开源软件镜像站
# ${codename} - Generated by homelab-stack setup

deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename} main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-updates main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-backports main restricted universe multiverse
deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-security main restricted universe multiverse

# 预发布软件源（可选）
# deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename}-proposed main restricted universe multiverse
EOF
  
  log_info "已写入清华源配置到 /etc/apt/sources.list"
  
  # Alternative mirrors (can be swapped)
  cat > /etc/apt/sources.list.available-mirrors <<'EOF'
# Available Chinese mirrors for Ubuntu/Debian
# Uncomment and replace in sources.list as needed

# 清华大学 TUNA (推荐)
# deb https://mirrors.tuna.tsinghua.edu.cn/ubuntu/ ${codename} main restricted universe multiverse

# 阿里云
# deb https://mirrors.aliyun.com/ubuntu/ ${codename} main restricted universe multiverse

# 中科大 USTC
# deb https://mirrors.ustc.edu.cn/ubuntu/ ${codename} main restricted universe multiverse

# 网易
# deb https://mirrors.163.com/ubuntu/ ${codename} main restricted universe multiverse

# 华为云
# deb https://mirrors.huaweicloud.com/ubuntu/ ${codename} main restricted universe multiverse
EOF
  
  log_info "已创建备用镜像列表: /etc/apt/sources.list.available-mirrors"
  
  # Update package index
  log_info "正在更新软件包索引..."
  if apt-get update; then
    log_info "软件包索引更新成功 ✓"
  else
    log_warn "软件包索引更新失败，请检查网络连接"
  fi
}

# =============================================================================
# Alpine APK Mirror Setup
# =============================================================================
setup_alpine_mirrors() {
  log_info "检测到 Alpine Linux 系统"
  
  if [[ $EUID -ne 0 ]]; then
    log_error "需要 root 权限来修改 apk 源"
    return 1
  fi
  
  # Detect Alpine version
  local version
  version=$(grep "VERSION_ID" /etc/os-release | cut -d= -f2 | tr -d '"')
  local major_minor
  major_minor=$(echo "$version" | cut -d. -f1,2)
  
  log_info "Alpine 版本: $version"
  
  # Backup original repositories
  if [[ -f "/etc/apk/repositories" ]]; then
    mkdir -p "$BACKUP_DIR"
    cp /etc/apk/repositories "$BACKUP_DIR/repositories"
    log_info "已备份原始配置到: $BACKUP_DIR/repositories"
  fi
  
  # Generate new repositories with USTC mirror (中科大)
  cat > /etc/apk/repositories <<EOF
# 中科大开源镜像站
# Alpine ${major_minor}

https://mirrors.ustc.edu.cn/alpine/v${major_minor}/main
https://mirrors.ustc.edu.cn/alpine/v${major_minor}/community

# 测试分支（可选）
# https://mirrors.ustc.edu.cn/alpine/edge/testing
EOF
  
  log_info "已写入中科大源配置到 /etc/apk/repositories"
  
  # Alternative mirrors
  cat > /etc/apk/repositories.available-mirrors <<EOF
# Available Chinese mirrors for Alpine Linux
# Uncomment and replace in repositories as needed

# 中科大 USTC (推荐)
# https://mirrors.ustc.edu.cn/alpine/v${major_minor}/main
# https://mirrors.ustc.edu.cn/alpine/v${major_minor}/community

# 清华大学 TUNA
# https://mirrors.tuna.tsinghua.edu.cn/alpine/v${major_minor}/main
# https://mirrors.tuna.tsinghua.edu.cn/alpine/v${major_minor}/community

# 阿里云
# https://mirrors.aliyun.com/alpine/v${major_minor}/main
# https://mirrors.aliyun.com/alpine/v${major_minor}/community
EOF
  
  log_info "已创建备用镜像列表: /etc/apk/repositories.available-mirrors"
  
  # Update package index
  log_info "正在更新软件包索引..."
  if apk update; then
    log_info "软件包索引更新成功 ✓"
  else
    log_warn "软件包索引更新失败，请检查网络连接"
  fi
}


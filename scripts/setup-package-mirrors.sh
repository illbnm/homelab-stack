  fi
}

# =============================================================================
# Restore original mirrors
# =============================================================================
restore_mirrors() {
  log_info "恢复原始镜像源配置..."
  
  # Find the most recent backup
  local latest_backup
  latest_backup=$(ls -dt /tmp/pkg-mirror-backup-* 2>/dev/null | head -1)
  
  if [[ -z "$latest_backup" ]]; then
    log_error "未找到备份文件"
    return 1
  fi
  
  log_info "使用备份: $latest_backup"
  
  # Restore based on system type
  if [[ -f "$latest_backup/sources.list" ]]; then
    cp "$latest_backup/sources.list" /etc/apt/sources.list
    log_info "已恢复 /etc/apt/sources.list"
  fi
  
  if [[ -d "$latest_backup/sources.list.d" ]]; then
    rm -rf /etc/apt/sources.list.d
    cp -r "$latest_backup/sources.list.d" /etc/apt/
    log_info "已恢复 sources.list.d 目录"
  fi
  
  if [[ -f "$latest_backup/repositories" ]]; then
    cp "$latest_backup/repositories" /etc/apk/repositories
    log_info "已恢复 /etc/apk/repositories"
  fi
  
  log_info "恢复完成 ✓"
}

# =============================================================================
# Main
# =============================================================================
usage() {
  cat <<EOF
用法:
  $0 [选项]

选项:
  --setup     配置国内镜像源（默认）
  --restore   恢复原始镜像源
  --help      显示帮助信息

支持的系统:
  - Ubuntu/Debian (apt)
  - Alpine Linux (apk)

示例:
  sudo $0 --setup
  sudo $0 --restore

注意:
  此脚本需要 root 权限运行
EOF
  exit 0
}

# Parse arguments
ACTION="${1:---setup}"

case "$ACTION" in
  --setup)
    ;;
  --restore)
    restore_mirrors
    exit $?
    ;;
  --help|-h)
    usage
    ;;
  *)
    log_error "未知参数: $ACTION"
    usage
    ;;
esac

# Check root
if [[ $EUID -ne 0 ]]; then
  log_error "此脚本需要 root 权限运行"
  echo "请使用: sudo $0"
  exit 1
fi

# Interactive prompt
echo -e "\n${BOLD}${BLUE}=== 软件包管理器镜像源配置 ===${NC}\n"
read -p "是否在中国大陆部署? (y/N): " -n 1 -r
echo

if [[ ! $REPLY =~ ^[Yy]$ ]]; then
  log_info "已取消配置"
  exit 0
fi

# Detect OS and setup mirrors
if [[ -f "/etc/debian_version" ]]; then
  # Debian
  setup_debian_mirrors
elif [[ -f "/etc/lsb-release" ]] && grep -q "Ubuntu" /etc/lsb-release 2>/dev/null; then
  # Ubuntu
  setup_ubuntu_mirrors
elif [[ -f "/etc/alpine-release" ]]; then
  # Alpine
  setup_alpine_mirrors
else
  log_error "不支持的操作系统"
  log_info "仅支持: Ubuntu, Debian, Alpine Linux"
  exit 1
fi

echo -e "\n${GREEN}${BOLD}✓ 软件包镜像源配置完成${NC}\n"
echo "备份目录: $BACKUP_DIR"
echo ""
echo "测试安装速度:"
echo "  apt: sudo apt-get install <package>"
echo "  apk: sudo apk add <package>"
echo ""
echo "恢复原配置:"
echo "  sudo $0 --restore"
